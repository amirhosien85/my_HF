def sanitize(text: str) -> str:
    """Strip the prohibited words if the model slips."""
    cleaned = text
    for word in PROHIBITED_WORDS:
        cleaned = cleaned.replace(word + "،", "").replace(word, "رفیق")
    return cleaned
